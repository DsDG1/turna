#!/usr/bin/env python3
"""Prepare a Turna checkout for an unsigned OHOS hap build in CI.

The committed ``ohos/`` tree carries state that only exists on the companion
build machine (AGENTS.md §9.1): DevEco fills ``build-profile.json5`` with
absolute Windows paths to a local debug certificate, and the npm/ohpm
lockfiles are resolved against that machine's fork-SDK checkout. Most of it
regenerates during ``flutter build hap`` — the fork's installHvigorPlugin
rewrites ``ohos/package.json`` against the current SDK, ``ohpm install --all``
re-resolves dependencies, and updateLocalProperties rewrites
``local.properties`` from DEVECO_SDK_HOME / NODE_HOME. The one invasive change
CI needs is stripping the signing config:

* the fork's gate (flutter_tools ``checkOhosSignedInfo``) rejects an *empty*
  ``signingConfigs`` list but accepts an absent key;
* with no product ``signingConfig``, hvigor emits an unsigned hap — the same
  artifact DevEco produces for the post-hoc release-signing flow.

Stdlib only on purpose: ``make test-python`` runs ``unittest`` without any
pip step, and this tool must run identically in CI and on the build machine.

Usage:
    python tool/ohos_ci_prepare.py prep-unsigned --root <repo root>
"""

from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import sys

# Machine-generated by DevEco's "Automatically generate signature"; regenerated
# the same way on every machine that configures signing. Regenerated, not
# hand-edited, so the stable formatting below is a safe anchor.
_SIGNING_BLOCK_KEY = "signingConfigs"
_PRODUCT_SIGNING_LINE = re.compile(r"^[ \t]*signingConfig[ \t]*:[^\n]*\n?", re.MULTILINE)

# Lockfiles and dependency trees resolved against the build machine's paths.
# ``ohos/package.json`` is deliberately NOT pruned: the fork's
# installHvigorPlugin deletes and rewrites it against the current SDK checkout
# before every hap build.
_PRUNE_FILES = (
    "ohos/package-lock.json",
    "ohos/entry/oh-package-lock.json5",
    "ohos/local.properties",
)
_PRUNE_DIRS = (
    "ohos/node_modules",
    "ohos/oh_modules",
    "ohos/entry/oh_modules",
    "ohos/build",
    "ohos/entry/build",
)


def strip_signing(text: str) -> str:
    """Return ``text`` without the ``signingConfigs`` member or any product
    ``signingConfig`` reference, so hvigor builds an unsigned hap and the
    fork's empty-list gate stays satisfied (the key must be *absent*, not
    emptied — see the module docstring)."""

    start = text.find(f"{_SIGNING_BLOCK_KEY}:")
    if start != -1:
        # Bracket-match from the opening '[' of the block to its ']' plus the
        # trailing comma. Values are DevEco-generated paths and passwords, so
        # no '[' or ']' can appear inside the quoted strings; the final
        # assertions below fail loudly if that assumption ever breaks.
        opening = text.find("[", start)
        if opening == -1:
            raise ValueError("signingConfigs found but no '[' follows it")
        depth = 0
        end = -1
        for i in range(opening, len(text)):
            ch = text[i]
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    end = i
                    break
        if end == -1:
            raise ValueError("signingConfigs block is never closed")
        # Swallow the newline after the removed member so the app block does
        # not gain a blank line on every run (idempotence).
        line_start = text.rfind("\n", 0, start) + 1
        after = end + 1
        if text[after : after + 1] == ",":
            after += 1
        while after < len(text) and text[after] in " \t":
            after += 1
        if after < len(text) and text[after] == "\n":
            after += 1
        text = text[:line_start] + text[after:]
    text = _PRODUCT_SIGNING_LINE.sub("", text)
    assert_no_signing(text)
    return text


def assert_no_signing(text: str) -> None:
    """Fail if any signing reference or bracket imbalance survives the strip.

    The bracket check is what makes the naive bracket matcher above safe: if a
    future DevEco ever emits '[' or ']' inside a quoted material value, the
    strip cuts at the wrong place and this assertion rejects the result
    instead of letting a corrupt build-profile reach hvigor."""

    if re.search(r"signingConfigs?\s*:", text):
        raise ValueError("a signingConfigs/signingConfig reference survived the strip")
    for opener, closer in (("[", "]"), ("{", "}")):
        if text.count(opener) != text.count(closer):
            raise ValueError(f"unbalanced {opener}{closer} after the strip")


def prep_unsigned(root: pathlib.Path) -> list[str]:
    """Prune machine-local state and strip the signing config under ``root``.

    Returns the human-readable list of removed paths (locks, dependency
    trees, stale build outputs); the build-profile rewrite is reported by the
    caller."""

    removed: list[str] = []
    for rel in _PRUNE_FILES:
        path = root / rel
        if path.is_file():
            path.unlink()
            removed.append(rel)
    for rel in _PRUNE_DIRS:
        path = root / rel
        if path.is_dir():
            shutil.rmtree(path)
            removed.append(rel + "/")

    profile = root / "ohos" / "build-profile.json5"
    original = profile.read_text(encoding="utf-8")
    stripped = strip_signing(original)
    if stripped != original:
        profile.write_text(stripped, encoding="utf-8", newline="\n")
    return removed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("prep-unsigned",))
    parser.add_argument(
        "--root",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent,
        help="repository root (default: the checkout this tool lives in)",
    )
    args = parser.parse_args()

    root = args.root.resolve()
    if not (root / "ohos" / "build-profile.json5").is_file():
        print(f"not a Turna checkout: {root}", file=sys.stderr)
        return 2

    removed = prep_unsigned(root)
    for rel in removed:
        print(f"pruned {rel}")
    print("stripped signing config from ohos/build-profile.json5 (absent = unsigned hap)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
